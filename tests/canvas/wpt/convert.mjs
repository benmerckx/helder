// web-platform-tests' Canvas 2D tests (html/canvas/element: paths, fills
// and strokes, line styles, compositing, transforms, rectangles) as one
// TypeScript module, cases.ts, for the canvas lane (wpt.ts: helder;
// chrome.mjs --wpt: Chromium). Each test's body as WPT wrote it, its
// harness's functions (_assertPixel, _assertSame, assert_throws_js...)
// harness.ts's. Tests that need a document, images, a promise, shadows,
// filters or typed arrays are left out (helder's TypeScript has no typed
// arrays yet; helder.canvas no shadows or filters yet).
//
//   git clone --filter=blob:none --sparse --depth 1 https://github.com/web-platform-tests/wpt.git
//   node tests/canvas/wpt/convert.mjs <wpt checkout>
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { execSync } from "node:child_process";

const root = process.argv[2];
const dirs = ["path-objects", "fill-and-stroke-styles", "line-styles", "compositing", "transformations", "drawing-rectangles-to-the-canvas"];
const skip = [/document\b/, /window\b/, /\bt\.(step|done)/, /\bawait\b/, /createImageBitmap/, /new Image\b/, /Uint8ClampedArray|Float32Array|Uint8Array/,
	/OffscreenCanvas/, /shadow/i, /\bfilter\b/, /\.data\[[^\]]*\]\s*=[^=]/, /toDataURL|toBlob/, /deferTest|promise_test|step_func|_done\(|_timeout/,
	/drawFocusIfNeeded|scrollPathIntoView|HitRegion|getContextAttributes/, /\b\d+n\b/, /\bfont\b/, /\bcolorSpace\b/, /_assertGreen/, /\bSymbol\b/,
	/\bProxy\b/, /\bReflect\b/, /assert_regexp_match/, /\bvalueOf\b|\btoString\b/, /\bDOMMatrixReadOnly\b|\bDOMPoint\b/, /\bwith\b\s*\(/,
	/createPattern\(\s*['"]?img/, /\bimg\b/, /\bvideo\b/, /\bdrawImage\(\s*canvas\s*,/, /\bcanvas\.(width|height)\s*=/, /\bdescriptor\b/,
	/Object\.getOwnPropertyDescriptor|Object\.getPrototypeOf|__proto__|\.prototype\b/, /\bconsole\b/];
// (tests whose code helder's TypeScript does not compile: a member the DOM has and helder's facade lacks...; name: why)
const excluded = new Map(readFileSync("tests/canvas/wpt/excluded.txt", "utf8").split("\n").filter(l => l.trim() !== "" && !l.startsWith("#")).map(l => [l.split(":")[0].trim(), l]));
const cases = [];
let total = 0, skipped = 0;
for (const d of dirs)
	for (const f of readdirSync(`${root}/html/canvas/element/${d}`).filter(f => f.endsWith(".html") && !f.includes("-manual") && !f.includes("-ref")).sort()) {
		const html = readFileSync(`${root}/html/canvas/element/${d}/${f}`, "utf8");
		const m = html.match(/_addTest\(function\(canvas, ctx\) \{\n([\s\S]*?)\n\}\);\n<\/script>/);
		if (!m) continue;
		total++;
		const body = m[1];
		if (skip.some(r => r.test(body)) || excluded.has(f.slice(0, -5))) { skipped++; continue; }
		const size = html.match(/<canvas id="c" class="output" width="(\d+)" height="(\d+)"/);
		const name = f.slice(0, -5);
		cases.push(`\t{ name: ${JSON.stringify(name)}, width: ${size ? size[1] : 100}, height: ${size ? size[2] : 50}, run: function (canvas: Canvas, ctx: CanvasRenderingContext2D) {\n${body.replace(/^/gm, "\t\t")}\n\t} },`);
	}
const sha = execSync("git rev-parse HEAD", { cwd: root, encoding: "utf8" }).trim();
writeFileSync("tests/canvas/wpt/cases.ts", `// @ts-nocheck
// Generated by tests/canvas/wpt/convert.mjs from web-platform-tests
// (https://github.com/web-platform-tests/wpt, ${sha}, html/canvas/element:
// ${dirs.join(", ")}); its tests' bodies as WPT wrote them. WPT's code is
// under the 3-Clause BSD License, (c) web-platform-tests contributors.
// ${cases.length} of ${total} tests (${skipped} left out: see convert.mjs).
import { Canvas, Path2D, DOMMatrix, ImageData, CanvasGradient, CanvasPattern, CanvasRenderingContext2D } from "helder/canvas";
import { _assert, _assertSame, _assertDifferent, _assertPixel, _assertPixelApprox, assert_throws_js, assert_throws_dom, assert_equals, assert_not_equals, assert_true, assert_false } from "./harness";

export const cases = [
${cases.join("\n")}
];
`);
console.log(`convert.mjs: ${cases.length} of ${total} tests (${skipped} left out)`);
