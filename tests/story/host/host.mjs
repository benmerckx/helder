// The story host, headless and as the desktop studio runs it (bun run test story-host):
//
//   node tests/story/host/host.mjs gen <dir> [screens]     the stories' program's sources into <dir>/gen
//   node tests/story/host/host.mjs measure <dir> [screens]  both run, measured: <dir>/results.md
//   node tests/story/host/host.mjs project <dir> [screens]  the same stories as a project for the studio
//                                                          (<dir>/Todo.hx, <dir>/Screens.story.hx: the studio-web lane's 50 screens)
//
// gen writes BenchStories.hx: screens stories (50 by default) of
// examples/todo's list, each its own list (0 to 24 items, some done, a
// filter), at a window's size and a phone's, in five flows; and BenchHost's
// main (helder.story.Host: every screen mounted in one program, drawn
// offscreen and read back, natively; a dev build, headless, as the
// studio's). measure starts it and times the start to every screen's first
// frame, the memory then (the process's resident set and proportional set,
// /proc/<pid>/smaps_rollup), and the host's frames: one screen focused
// (drawn every frame) while the others are still. Then the desktop studio
// itself (apps/studio, headless, helder run) on the same stories as a
// project (project's): its one preview process (helder.story.NativeHost:
// frames as shared GPU textures, or through shared memory where the GPU has
// none: llvmpipe), the project opened to every screen shown (from the
// studio's open, the cold build in it, and from the host process's start),
// the memory of the host and of the studio then (held there:
// --hold-while), and an inspector's colour change on a zoomed screen to the
// host's frame showing it (a live literal: tests/story/host/studio.json).
// The process a screen the studio ran before (each story its own dev
// build's process) took 0.8 to 3.3 s to every first frame and 6.1 GB
// resident (2.8 GB Pss) for these 50 screens: the table's last row, from
// the lane's last run of it. Linux only (/proc).
import { spawn } from 'node:child_process';
import { mkdirSync, writeFileSync, readFileSync, existsSync, rmSync, readdirSync } from 'node:fs';
import path from 'node:path';

const [mode, dir, count] = process.argv.slice(2);
const N = Number(count ?? 50);
const flows = ['Lists', 'Done', 'Phone', 'Filters', 'Long'];

function stories() {
	const out = [];
	for (let i = 0; i < N; i++) {
		const flow = flows[i % flows.length];
		const phone = flow === 'Phone';
		const items = (i * 7) % 25, filter = flow === 'Done' ? 'done' : flow === 'Filters' ? (i % 2 ? 'active' : 'all') : 'all';
		out.push({ name: `${flow}/Screen ${i + 1}`, phone, items, filter });
	}
	return out;
}

// the stories as a project for the studio: dir/Todo.hx, dir/Screens.story.hx
function writeProject(dir) {
	mkdirSync(dir, { recursive: true });
	const here = path.dirname(new URL(import.meta.url).pathname);
	writeFileSync(path.join(dir, 'Todo.hx'), readFileSync(path.join(here, '../../../examples/todo/Todo.hx')));
	const lines = ['// ' + N + ' screens of the todo list (generated by tests/story/host/host.mjs project)', 'import Todo.Item;', 'import helder.story.Story;', ''];
	stories().forEach((s, i) => {
		const size = s.phone ? '' : 'width: 480, height: 560, ';
		lines.push(`final s${i} = story({name: "${s.name}", ${size}render: () -> todo(${s.items}, "${s.filter}")});`);
	});
	lines.push('', '// (n items, every third done, a filter)', 'private function todo(n:Int, filter:String):helder.view.View {', '\tvar t = new Todo();',
		'\tvar list = [for (i in 0...n) new Item("Item " + (i + 1))];', '\tfor (i in 0...n) if (i % 3 == 1) list[i].done(true);', '\tt.todos(list);',
		'\tt.filter(filter);', '\treturn t.view();', '}');
	writeFileSync(path.join(dir, 'Screens.story.hx'), lines.join('\n') + '\n');
}

if (mode === 'project') {
	writeProject(dir);
	process.exit(0);
}

if (mode === 'gen') {
	const gen = path.join(dir, 'gen');
	mkdirSync(gen, { recursive: true });
	const lines = ['// helder.story.Host\'s bench: ' + N + ' stories of examples/todo (generated by tests/story/host/host.mjs)', 'import helder.story.Story;', ''];
	stories().forEach((s, i) => {
		const size = s.phone ? '' : 'width: 480, height: 560, ';
		lines.push(`final s${i} = story({name: "${s.name}", ${size}render: () -> BenchHost.todo(${s.items}, "${s.filter}")});`);
	});
	writeFileSync(path.join(gen, 'BenchStories.hx'), lines.join('\n') + '\n');
	writeFileSync(path.join(gen, 'BenchHost.hx'), `// every story in one program (helder.story.Host), offscreen: open to every first frame, then frames (generated)
import Todo.Item;
import helder.story.Host;

class BenchHost {
	public static function todo(n:Int, filter:String):helder.view.View {
		var t = new Todo();
		var list = [for (i in 0...n) new Item("Item " + (i + 1))];
		for (i in 0...n) if (i % 3 == 1) list[i].done(true);
		t.todos(list);
		t.filter(filter);
		return t.view();
	}

	static function main() {
		var t0 = haxe.Timer.stamp();
		var host = new Host(helder.story.Stories.of("BenchStories"), new HeadlessHost());
		var names = [for (s in host.screens) s.name];
		host.show(names);
		var turns = 0;
		while (Lambda.exists(host.screens, s -> s.version == 0)) {
			host.frame(haxe.Timer.stamp());
			turns++;
		}
		var open = haxe.Timer.stamp() - t0;
		// (each screen's first frame, for the driver to compare with its process's)
		var rt:HeadlessHost = cast host.runtime;
		for (i => s in host.screens) {
			var head = haxe.io.Bytes.alloc(16);
			head.setInt32(4, s.width);
			head.setInt32(8, s.height);
			var o = sys.io.File.write(Sys.args()[0] + "/s" + i + ".rgba");
			o.write(head);
			o.write(rt.pixels.get(s.name));
			o.close();
		}
		Sys.println('host: shown ' + host.screens.length + ' ' + Math.round(open * 1000) + ' ' + turns);
		// (the memory read now, by the driver: the host waits for it)
		Sys.stdin().readLine();
		// one focused: it draws every frame, the others are still
		host.focus(names[0]);
		var frames = 120, t1 = haxe.Timer.stamp(), drawn = 0;
		for (_ in 0...frames) drawn += host.frame(haxe.Timer.stamp());
		var still = haxe.Timer.stamp() - t1;
		// nothing focused, nothing changed: no screen draws
		host.focus(null);
		var t2 = haxe.Timer.stamp(), idle = 0;
		for (_ in 0...frames) idle += host.frame(haxe.Timer.stamp());
		var quiet = haxe.Timer.stamp() - t2;
		// only half shown: the other half suspended
		host.show(names.slice(0, Std.int(names.length / 2)));
		Sys.println('host: focused ' + Math.round(still / frames * 100000) / 100 + ' ' + drawn + ' idle ' + Math.round(quiet / frames * 100000) / 100 + ' ' + idle);
	}
}
`);
	process.exit(0);
}

