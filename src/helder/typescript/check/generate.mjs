// Generates Kind.hx and Syntax.hx beside this file from a typescript package
// (node src/helder/typescript/check/generate.mjs [<package dir>]): the
// SyntaxKind names the frontend is written against, the layout constants of
// tsgo's binary AST, and an accessor per child property name. The numbers
// a kind or a child property has in the installed version are read from it
// at run time (Tables.hx), by name, so a newer TypeScript works without
// regenerating; this only needs rerunning to use new syntax.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url));
const pkg = path.resolve(process.argv[2] ?? 'node_modules/typescript');
const load = rel => import(pathToFileURL(path.join(pkg, rel)).href);
const {SyntaxKind} = await load('dist/ast/index.js');
const {childProperties} = await load('dist/api/node/protocol.generated.js');
const protocol = await load('dist/api/node/protocol.js');
const version = JSON.parse(fs.readFileSync(path.join(pkg, 'package.json'), 'utf8')).version;
const kinds = Object.entries(SyntaxKind).filter(([, v]) => typeof v === 'number');
const names = [...new Set(Object.values(childProperties).flat())].sort();
const lists = new Set(['arguments', 'children', 'clauses', 'declarations', 'elements', 'heritageClauses', 'members', 'modifiers', 'parameters', 'properties', 'statements', 'tags', 'templateSpans', 'typeArguments', 'typeParameters', 'types']);
const method = n => n === 'children' ? 'jsxChildren' : n;
const header = [`// Generated by src/helder/typescript/check/generate.mjs from typescript@${version}. Do not edit.`, 'package helder.typescript.check;', ''];

const kind = [...header, 'enum abstract Kind(Int) to Int {'];
for (const [k, v] of kinds) kind.push(`\tvar Kind${k} = ${v};`);
kind.push('', '\t@:op(A > B) static function gt(a:Kind, b:Kind):Bool;', '', '\t@:op(A < B) static function lt(a:Kind, b:Kind):Bool;', '', '\t@:op(A >= B) static function gte(a:Kind, b:Kind):Bool;', '', '\t@:op(A <= B) static function lte(a:Kind, b:Kind):Bool;', '');
const byValue = new Map();
for (const [k, v] of kinds) if (!/^(First|Last|Count)/.test(k) && !byValue.has(v)) byValue.set(v, k);
kind.push(`\tpublic static final names = [${[...Array(SyntaxKind.Count).keys()].map(i => JSON.stringify(byValue.get(i) ?? '')).join(', ')}];`);
kind.push('', '\tpublic function toString():String return this == -1 ? "NodeList" : names[this];', '}', '');
fs.writeFileSync(path.join(here, 'Kind.hx'), kind.join('\n'));

const syntax = [...header, 'import helder.typescript.check.Ast;', '', '// The binary AST layout this reader is written for (Tables checks the installed one).', 'class Protocol {'];
for (const k of Object.keys(protocol).filter(k => /^[A-Z_0-9]+$/.test(k) && typeof protocol[k] === 'number'))
	syntax.push(`\tpublic static inline var ${k} = ${protocol[k] > 0x7fffffff ? protocol[k] | 0 : protocol[k]};`);
syntax.push(`\t// the child property names, in the order of the accessors' numbers`, `\tpublic static final properties = [${names.map(n => JSON.stringify(n)).join(', ')}];`, '}', '');
syntax.push('// Named child accessors: lists return their elements, single children null when absent.', 'class Children {');
names.forEach((n, i) => syntax.push(...(i > 0 ? [''] : []), lists.has(n) ? `\tpublic inline function ${method(n)}():Array<Node> return list(${i});` : `\tpublic inline function ${method(n)}():Node return child(${i});`));
syntax.push('', '\tfunction child(property:Int):Node throw "abstract";', '', '\tfunction list(property:Int):Array<Node> throw "abstract";', '}', '');
fs.writeFileSync(path.join(here, 'Syntax.hx'), syntax.join('\n'));
console.log(`typescript@${version}: ${kinds.length} kinds, ${names.length} child properties`);
