import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {spawnSync} from 'node:child_process';
const version='17.0.0';
const dir=path.resolve('.cache/unicode-'+version);fs.mkdirSync(dir,{recursive:true});
const names=['UnicodeData.txt','DerivedNormalizationProps.txt','NormalizationTest.txt','LICENSE.txt'];
const files={};
for(const name of names){
  const file=path.join(dir,name),url=name==='LICENSE.txt'?'https://www.unicode.org/license.txt':`https://www.unicode.org/Public/${version}/ucd/${name}`;
  if(!fs.existsSync(file)){const r=spawnSync('curl',['-fsSL','--max-time','60',url,'-o',file],{encoding:'utf8'});if(r.status!==0)throw Error(r.stderr);}
  files[name]={url,sha256:crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex')};
}
const manifestFile='runtime/tshx/runtime/unicode/manifest.json';
if(fs.existsSync(manifestFile)){
  const old=JSON.parse(fs.readFileSync(manifestFile,'utf8'));
  for(const name of names)if(old.files[name].sha256!==files[name].sha256)throw Error('Unicode source hash changed: '+name);
}
const excluded=new Set();
for(const line of fs.readFileSync(path.join(dir,names[1]),'utf8').split('\n')){
  const fields=line.split('#')[0].split(';').map(s=>s.trim());if(fields[1]!=='Full_Composition_Exclusion')continue;
  const range=fields[0].split('..').map(s=>parseInt(s,16));for(let cp=range[0];cp<=(range[1]??range[0]);cp++)excluded.add(cp);
}
const dec=[],ccc=[],composition=[];
const hex=x=>x.toString(16);
for(const line of fs.readFileSync(path.join(dir,names[0]),'utf8').split('\n')){
  if(!line)continue;const f=line.split(';'),cp=parseInt(f[0],16);
  if(Number(f[3]))ccc.push(`${hex(cp)}:${hex(Number(f[3]))}`);
  if(!f[5])continue;const compat=f[5].startsWith('<');const points=f[5].replace(/^<[^>]+> /,'').split(' ').map(s=>parseInt(s,16));
  dec.push(`${hex(cp)}:${compat?'k':'c'}:${points.map(hex).join(',')}`);
  if(!compat && points.length===2 && !excluded.has(cp))composition.push(`${hex(points[0])},${hex(points[1])}:${hex(cp)}`);
}
function literal(s){const parts=[];for(let i=0;i<s.length;i+=4096)parts.push(JSON.stringify(s.slice(i,i+4096)));return parts.join('+\n        ');}
let out='package tshx.runtime.unicode;\n// Generated by tools/generate-normalization.mjs from Unicode '+version+'.\n// Unicode-3.0 license: LICENSE.txt; inputs and hashes: manifest.json.\nclass NormalizationData {\n';
for(const [name,data] of [['decompositions',dec],['combining',ccc],['compositions',composition]])out+=`    public static function ${name}():String return\n        ${literal(data.join(';'))};\n`;
out+='}\n';
fs.mkdirSync(path.dirname(manifestFile),{recursive:true});fs.writeFileSync('runtime/tshx/runtime/unicode/NormalizationData.hx',out);
fs.copyFileSync(path.join(dir,'LICENSE.txt'),'runtime/tshx/runtime/unicode/LICENSE.txt');
fs.writeFileSync(manifestFile,JSON.stringify({version,files,counts:{decompositions:dec.length,combining:ccc.length,compositions:composition.length}},null,2)+'\n');
console.log({version,decompositions:dec.length,combining:ccc.length,compositions:composition.length});
